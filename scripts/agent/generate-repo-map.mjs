import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import {
  collectFiles,
  isRecord,
  pathExists,
  readJson,
  relativeToRoot,
  repositoryRoot,
} from "./lib.mjs";

const metadataPath = join(repositoryRoot, ".ai/repository-metadata.json");
const outputPath = join(repositoryRoot, ".ai/REPOSITORY_MAP.md");
const metadata = await readJson(metadataPath);
if (!isRecord(metadata) || !isRecord(metadata.project) || !Array.isArray(metadata.packages)) {
  throw new Error("Invalid .ai/repository-metadata.json");
}

const markdown = await renderRepositoryMap(metadata);
if (process.argv.includes("--check")) {
  const current = (await pathExists(outputPath)) ? await readFile(outputPath, "utf8") : "";
  if (current !== markdown) {
    console.error(".ai/REPOSITORY_MAP.md is stale. Run npm run agent:map.");
    process.exitCode = 1;
  } else {
    console.log("AI repository map is current.");
  }
} else {
  await writeFile(outputPath, markdown);
  console.log(`Generated ${relativeToRoot(outputPath)}.`);
}

async function renderRepositoryMap(metadataValue) {
  const project = metadataValue.project;
  const lines = [
    "<!-- Generated by scripts/agent/generate-repo-map.mjs. Do not edit manually. -->",
    "",
    `# ${stringValue(project.name)} repository map`,
    "",
    stringValue(project.summary),
    "",
    `**Architecture:** ${stringValue(project.architecture)}`,
    "",
    "## Workspace packages",
    "",
  ];

  for (const packageMetadata of metadataValue.packages) {
    if (!isRecord(packageMetadata)) {
      throw new Error("Repository package metadata must be an object");
    }
    const packagePath = stringValue(packageMetadata.path);
    const manifest = await readJson(join(repositoryRoot, packagePath, "package.json"));
    const files = await collectFiles(join(repositoryRoot, packagePath), {
      extensions: [".ts", ".tsx"],
    });
    lines.push(`### ${stringValue(packageMetadata.name)}`);
    lines.push("");
    lines.push(`- Path: \`${packagePath}\``);
    lines.push(`- Version: \`${isRecord(manifest) ? stringValue(manifest.version) : "unknown"}\``);
    lines.push(`- Responsibility: ${stringValue(packageMetadata.responsibility)}`);
    lines.push(`- TypeScript files: ${files.length}`);
    lines.push(`- Entrypoints: ${stringArray(packageMetadata.entrypoints).map(code).join(", ")}`);
    lines.push(`- Relevant changes: ${stringArray(packageMetadata.changeSignals).join("、")}`);
    lines.push("");
  }

  lines.push("## Change guides", "");
  for (const guide of Array.isArray(metadataValue.changeGuides) ? metadataValue.changeGuides : []) {
    if (!isRecord(guide)) {
      continue;
    }
    lines.push(`### ${stringValue(guide.when)}`, "");
    lines.push(`- Inspect: ${stringArray(guide.inspect).map(code).join(", ")}`);
    lines.push(`- Required checks: ${stringArray(guide.requiredChecks).map(code).join(", ")}`);
    lines.push("");
  }

  lines.push("## Important root files", "");
  for (const file of [
    "AGENTS.md",
    ".ai/task.schema.json",
    ".ai/architecture-rules.json",
    "package.json",
    "tsconfig.base.json",
    "eslint.config.js",
    "apps/activity/wrangler.jsonc",
    "assets/asset-pack.schema.json",
    "docs/ASSETS.md",
    "migrations/0001_initial.sql",
  ]) {
    lines.push(`- ${code(file)}`);
  }
  const raw = `${lines.join("\n")}\n`;
  try {
    const prettier = (await import("prettier")).default;
    return await prettier.format(raw, { parser: "markdown" });
  } catch {
    return raw;
  }
}

function stringValue(value) {
  if (typeof value !== "string") {
    throw new Error("Expected string metadata value");
  }
  return value;
}

function stringArray(value) {
  if (!Array.isArray(value) || value.some((item) => typeof item !== "string")) {
    throw new Error("Expected string array metadata value");
  }
  return value;
}

function code(value) {
  return `\`${value}\``;
}
